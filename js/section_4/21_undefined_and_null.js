// Undefined vs Null: Undefined and null are both primitive values in JavaScript, but they have different meanings and uses.

// Undefined: A variable that has been declared but has not been assigned a value is considered undefined. It indicates the absence of a value or that the variable has not been initialized.
let x;
console.log(x); 

// Null: A variable that has been explicitly assigned the value null is considered null. It represents the intentional absence of any object value.
let y = null;
console.log(y); 